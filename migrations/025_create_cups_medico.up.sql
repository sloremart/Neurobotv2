--   mezcla EMG/potenciales/infiltracion por especialistas distintos). SIESA solo modela
--   medico->asunto, no medico->CUPS; esta tabla cubre ese vacio.
-- Uso: si un CUPS tiene filas aqui, la busqueda de slots se restringe a esos medicos;
--   si no tiene, cae a asunto-only (comportamiento previo).
-- IMPORTANTE: el INSERT resuelve cup_id por codigo_cups en tiempo de ejecucion para ser
--   robusto si los AUTO_INCREMENT id divergen entre entornos.

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS cups_medico (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    cup_id     INT UNSIGNED NOT NULL COMMENT 'FK a cups_procedimientos.id (catalogo local)',
    medico_id  INT          NOT NULL COMMENT 'sis_medi.codigo de SIESA (cod_medi)',
    activo     TINYINT(1)   NOT NULL DEFAULT 1,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_cup_medico (cup_id, medico_id),
    INDEX idx_cup (cup_id),
    INDEX idx_medico (medico_id),
    CONSTRAINT fk_cups_medico_cup FOREIGN KEY (cup_id)
        REFERENCES cups_procedimientos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

